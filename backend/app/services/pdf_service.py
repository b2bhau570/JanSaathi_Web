"""
Jan Saathi AI — PDF report generation (reportlab).

⚠ All generated PDFs carry a prototype disclaimer.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm, mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


_DISCLAIMER = (
    "NON-DIAGNOSTIC CLINICAL TRIAGE NOTICE: Generated by the Jan Saathi AI Healthcare Platform. "
    "This document summarizes reported symptoms, vitals, and automated triage/OCR flags only and "
    "does NOT constitute a medical diagnosis or prescription. Review by a qualified Medical Officer is required."
)

_PRESCRIPTION_DISCLAIMER = (
    "CLINICAL PRESCRIPTION & TREATMENT PLAN — Jan Saathi AI Telemedicine Network. "
    "Authorized for dispensation and patient care only following licensed physician validation."
)

_NON_DIAGNOSTIC_FOOTER = (
    "NON-DIAGNOSTIC TRIAGE DISCLAIMER: Automated AI intake summaries, OCR extractions, and priority tiers "
    "are decision-support aids only and NEVER replace formal examination, diagnosis, or prescription by a qualified Medical Officer."
)


def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("CenterBold", parent=ss["Heading1"], alignment=TA_CENTER, fontSize=16))
    ss.add(ParagraphStyle("Disclaimer", parent=ss["Normal"], fontSize=8, textColor=colors.red, alignment=TA_CENTER))
    ss.add(ParagraphStyle("SectionHead", parent=ss["Heading2"], fontSize=12, spaceAfter=4))
    ss.add(ParagraphStyle("Field", parent=ss["Normal"], fontSize=10, spaceAfter=2))
    ss.add(ParagraphStyle("SmallRight", parent=ss["Normal"], fontSize=8, alignment=TA_RIGHT, textColor=colors.grey))
    return ss


def generate_case_receipt_pdf(case) -> bytes:
    """Generate a patient-facing receipt PDF (minimal info)."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    ss = _styles()
    story: list = []

    # Title
    story.append(Paragraph("Jan Saathi AI — Case Receipt", ss["CenterBold"]))
    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph(_DISCLAIMER, ss["Disclaimer"]))
    story.append(Spacer(1, 8 * mm))

    # Case info
    story.append(Paragraph("Case Information", ss["SectionHead"]))
    story.append(Paragraph(f"<b>Case ID:</b> {case.public_case_id}", ss["Field"]))
    story.append(Paragraph(f"<b>Patient:</b> {case.patient_name}", ss["Field"]))
    story.append(Paragraph(f"<b>Status:</b> {case.status}", ss["Field"]))
    story.append(Paragraph(f"<b>Priority:</b> {case.priority}", ss["Field"]))
    story.append(Paragraph(f"<b>Submitted:</b> {case.created_at.strftime('%Y-%m-%d %H:%M UTC')}", ss["Field"]))
    story.append(Spacer(1, 6 * mm))

    story.append(Paragraph("Chief Complaint", ss["SectionHead"]))
    story.append(Paragraph(case.chief_complaint, ss["Field"]))
    story.append(Spacer(1, 8 * mm))

    # Footer
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    story.append(Paragraph(f"Generated: {now_str}", ss["SmallRight"]))
    story.append(Spacer(1, 3 * mm))
    story.append(Paragraph(_NON_DIAGNOSTIC_FOOTER, ss["Disclaimer"]))

    doc.build(story)
    return buf.getvalue()


def generate_full_report_pdf(
    case,
    responses: list | None = None,
    measurements: list | None = None,
    treatment=None,
    treatment_items: list | None = None,
    notes: list | None = None,
    triage_decisions: list | None = None,
) -> bytes:
    """Generate a comprehensive doctor-facing case report PDF."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    ss = _styles()
    story: list = []

    # ── Header ─────────────────────────────────────────────────────────
    story.append(Paragraph("Jan Saathi AI — Case Report", ss["CenterBold"]))
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(_DISCLAIMER, ss["Disclaimer"]))
    story.append(Spacer(1, 8 * mm))

    # ── Patient ────────────────────────────────────────────────────────
    story.append(Paragraph("Patient Information", ss["SectionHead"]))
    info_data = [
        ["Case ID", case.public_case_id],
        ["Name", case.patient_name],
        ["Age", str(case.patient_age)],
        ["Gender", case.patient_gender],
        ["Contact", case.patient_contact or "—"],
        ["Language", case.preferred_language],
    ]
    t = Table(info_data, colWidths=[4 * cm, 12 * cm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(t)
    story.append(Spacer(1, 6 * mm))

    # ── Complaint ──────────────────────────────────────────────────────
    story.append(Paragraph("Chief Complaint", ss["SectionHead"]))
    story.append(Paragraph(case.chief_complaint, ss["Field"]))
    if case.complaint_duration:
        story.append(Paragraph(f"<b>Duration:</b> {case.complaint_duration}", ss["Field"]))
    if case.severity:
        story.append(Paragraph(f"<b>Self-reported severity:</b> {case.severity}", ss["Field"]))
    story.append(Spacer(1, 4 * mm))

    # Medical history
    if case.medical_history:
        story.append(Paragraph("Medical History", ss["SectionHead"]))
        story.append(Paragraph(case.medical_history, ss["Field"]))
        story.append(Spacer(1, 4 * mm))
    if case.allergies:
        story.append(Paragraph(f"<b>Allergies:</b> {case.allergies}", ss["Field"]))
    if case.current_medications:
        story.append(Paragraph(f"<b>Current medications:</b> {case.current_medications}", ss["Field"]))
    story.append(Spacer(1, 4 * mm))

    # ── Triage ─────────────────────────────────────────────────────────
    if triage_decisions:
        story.append(Paragraph("Triage Decisions", ss["SectionHead"]))
        for td in triage_decisions:
            prio = td.priority if hasattr(td, "priority") else td.get("priority", "")
            reason = td.reason if hasattr(td, "reason") else td.get("reason", "")
            story.append(Paragraph(f"<b>Priority:</b> {prio}", ss["Field"]))
            story.append(Paragraph(f"<b>Reason:</b> {reason}", ss["Field"]))
            story.append(Spacer(1, 2 * mm))
        story.append(Spacer(1, 4 * mm))

    # ── Interview responses ────────────────────────────────────────────
    if responses:
        story.append(Paragraph("Interview Responses", ss["SectionHead"]))
        for r in responses:
            q = r.question if hasattr(r, "question") else r.get("question", "")
            a = r.answer if hasattr(r, "answer") else r.get("answer", "")
            src = r.question_source if hasattr(r, "question_source") else r.get("question_source", "")
            story.append(Paragraph(f"<b>Q ({src}):</b> {q}", ss["Field"]))
            story.append(Paragraph(f"<b>A:</b> {a}", ss["Field"]))
            story.append(Spacer(1, 2 * mm))
        story.append(Spacer(1, 4 * mm))

    # ── Measurements ───────────────────────────────────────────────────
    if measurements:
        story.append(Paragraph("Vital Signs / Measurements", ss["SectionHead"]))
        m_data = [["Type", "Value", "Unit", "Source", "Quality", "Recorded"]]
        for m in measurements:
            if hasattr(m, "measurement_type"):
                row = [m.measurement_type, str(m.value), m.unit, m.source, m.signal_quality or "—", m.recorded_at.strftime("%H:%M")]
            else:
                row = [m.get("measurement_type",""), str(m.get("value","")), m.get("unit",""), m.get("source",""), m.get("signal_quality","—"), ""]
            m_data.append(row)
        mt = Table(m_data, repeatRows=1)
        mt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4472C4")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#D9E2F3")]),
        ]))
        story.append(mt)
        story.append(Spacer(1, 6 * mm))

    # ── Doctor notes ───────────────────────────────────────────────────
    if notes:
        story.append(Paragraph("Doctor Notes", ss["SectionHead"]))
        for n in notes:
            ntype = n.note_type if hasattr(n, "note_type") else n.get("note_type", "")
            content = n.content if hasattr(n, "content") else n.get("content", "")
            story.append(Paragraph(f"<b>[{ntype}]</b> {content}", ss["Field"]))
            story.append(Spacer(1, 2 * mm))
        story.append(Spacer(1, 4 * mm))

    # ── Treatment ──────────────────────────────────────────────────────
    if treatment:
        story.append(Paragraph("Treatment Plan", ss["SectionHead"]))
        is_final = treatment.is_finalized if hasattr(treatment, "is_finalized") else treatment.get("is_finalized", False)
        if not is_final:
            story.append(Paragraph(_PRESCRIPTION_DISCLAIMER, ss["Disclaimer"]))
            story.append(Spacer(1, 3 * mm))

        assessment = treatment.assessment if hasattr(treatment, "assessment") else treatment.get("assessment")
        if assessment:
            story.append(Paragraph(f"<b>Assessment:</b> {assessment}", ss["Field"]))
        disposition = treatment.disposition if hasattr(treatment, "disposition") else treatment.get("disposition")
        if disposition:
            story.append(Paragraph(f"<b>Disposition:</b> {disposition}", ss["Field"]))
        warnings_val = treatment.warnings if hasattr(treatment, "warnings") else treatment.get("warnings")
        if warnings_val:
            story.append(Paragraph(f"<b>Warnings:</b> {warnings_val}", ss["Field"]))
        follow_up = treatment.follow_up_instructions if hasattr(treatment, "follow_up_instructions") else treatment.get("follow_up_instructions")
        if follow_up:
            story.append(Paragraph(f"<b>Follow-up:</b> {follow_up}", ss["Field"]))
        story.append(Spacer(1, 4 * mm))

        items = treatment_items or (treatment.items if hasattr(treatment, "items") else [])
        if items:
            story.append(Paragraph("Medications / Items", ss["SectionHead"]))
            rx_header = ["#", "Medicine", "Strength", "Dosage", "Route", "Frequency", "Duration"]
            rx_data = [rx_header]
            for idx, item in enumerate(items, 1):
                if hasattr(item, "medicine_name"):
                    row = [str(idx), item.medicine_name, item.strength or "—", item.dosage or "—",
                           item.route or "—", item.frequency or "—", item.duration or "—"]
                else:
                    row = [str(idx), item.get("medicine_name",""), item.get("strength","—"),
                           item.get("dosage","—"), item.get("route","—"),
                           item.get("frequency","—"), item.get("duration","—")]
                rx_data.append(row)
            rx_t = Table(rx_data, repeatRows=1)
            rx_t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#548235")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#E2EFDA")]),
            ]))
            story.append(rx_t)
            story.append(Spacer(1, 6 * mm))

    # ── Footer ─────────────────────────────────────────────────────────
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    story.append(Spacer(1, 10 * mm))
    story.append(Paragraph(f"Report generated: {now_str}", ss["SmallRight"]))
    story.append(Paragraph(_NON_DIAGNOSTIC_FOOTER, ss["Disclaimer"]))

    doc.build(story)
    return buf.getvalue()


def generate_referral_pdf(
    case,
    measurements: list | None = None,
    documents: list | None = None,
    notes: list | None = None,
    triage_decisions: list | None = None,
    doctor=None,
) -> bytes:
    """
    Generate a 1-Click Inter-Facility Referral Slip PDF (DHH / Medical College transfer)
    pre-filled with patient demographics, 30-second averaged vitals, abnormal OCR lab flags,
    stabilization notes, and a 108 Ambulance referral header.
    """
    import json

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=1.8 * cm, bottomMargin=1.8 * cm)
    ss = _styles()
    story: list = []

    # ── 108 Ambulance / Inter-Facility Referral Header ───────────────────
    header_tbl = Table(
        [[
            Paragraph(
                "<b>108 AMBULANCE &amp; INTER-FACILITY EMERGENCY REFERRAL SLIP</b><br/>"
                "<font size='9'>PHC / CHC / Tele-Health Kiosk Transfer to District Headquarters Hospital (DHH) / Medical College</font>",
                ParagraphStyle("RefHead", parent=ss["Normal"], textColor=colors.white, alignment=TA_CENTER, fontSize=12),
            )
        ]],
        colWidths=[17 * cm],
    )
    header_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#9B1C1C")),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(header_tbl)
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(_DISCLAIMER, ss["Disclaimer"]))
    story.append(Spacer(1, 5 * mm))

    # ── Referral Metadata & Patient Demographics ─────────────────────────
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    ref_doc_name = getattr(doctor, "full_name", "Attending Medical Officer") if doctor else "Attending Medical Officer"
    ref_doc_reg = getattr(doctor, "registration_number", None) or "—"
    priority_str = str(getattr(case, "priority", "normal") or "normal").upper()

    story.append(Paragraph("1. Patient Demographics &amp; Transfer Details", ss["SectionHead"]))
    demo_rows = [
        ["Case ID", case.public_case_id, "Triage Urgency", f"<b>{priority_str}</b>"],
        ["Patient Name", case.patient_name, "Age / Gender", f"{case.patient_age} yrs / {case.patient_gender}"],
        ["Contact", case.patient_contact or "—", "Referral Time", now_str],
        ["Referring Doctor", ref_doc_name, "Reg. Number", ref_doc_reg],
        ["Target Facility", "Nearest DHH / Medical College", "Transport Mode", "108 Emergency Ambulance"],
    ]
    demo_cells = [
        [Paragraph(str(c), ParagraphStyle("Cell", parent=ss["Normal"], fontSize=9)) for c in r]
        for r in demo_rows
    ]
    demo_tbl = Table(demo_cells, colWidths=[3.3 * cm, 5.2 * cm, 3.3 * cm, 5.2 * cm])
    demo_tbl.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F3F4F6")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F3F4F6")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(demo_tbl)
    story.append(Spacer(1, 5 * mm))

    # ── Presenting Complaint & Allergies ─────────────────────────────────
    story.append(Paragraph("2. Presenting Complaint &amp; Risk History", ss["SectionHead"]))
    story.append(Paragraph(f"<b>Chief Complaint:</b> {case.chief_complaint}", ss["Field"]))
    if case.complaint_duration:
        story.append(Paragraph(f"<b>Duration:</b> {case.complaint_duration}", ss["Field"]))
    story.append(Paragraph(f"<b>Known Allergies:</b> {case.allergies or 'None documented'}", ss["Field"]))
    story.append(Paragraph(f"<b>Medical History:</b> {case.medical_history or 'None documented'}", ss["Field"]))
    story.append(Spacer(1, 5 * mm))

    # ── 30-Second Averaged Hardware / Clinical Vitals ────────────────────
    story.append(Paragraph("3. Averaged Vital Signs Summary", ss["SectionHead"]))
    grouped_vitals: dict[str, list[float]] = {}
    vital_units: dict[str, str] = {}
    for m in (measurements or []):
        mtype = (m.measurement_type if hasattr(m, "measurement_type") else m.get("measurement_type", "")).lower().strip()
        try:
            mval = float(m.value if hasattr(m, "value") else m.get("value"))
        except (TypeError, ValueError):
            continue
        if mval <= 0:
            continue
        munit = m.unit if hasattr(m, "unit") else m.get("unit", "")
        if mtype == "temperature" and (mval > 45.0 or "f" in str(munit).lower()):
            mval = round((mval - 32.0) * 5.0 / 9.0, 2)
            munit = "°C"
        canonical = "systolic_bp" if mtype in ("blood_pressure", "bp", "sbp") else mtype
        grouped_vitals.setdefault(canonical, []).append(mval)
        if munit and canonical not in vital_units:
            vital_units[canonical] = str(munit)

    if grouped_vitals:
        v_rows = [["Vital Parameter", "Mean Reading", "Unit", "Samples"]]
        label_map = {
            "spo2": "Oxygen Saturation (SpO2)",
            "heart_rate": "Heart Rate (Pulse)",
            "temperature": "Body Temperature",
            "systolic_bp": "Systolic Blood Pressure",
            "respiratory_rate": "Respiratory Rate",
        }
        for key, vals in grouped_vitals.items():
            avg_val = round(sum(vals) / len(vals), 1)
            v_rows.append([label_map.get(key, key), str(avg_val), vital_units.get(key, "—"), str(len(vals))])
        vt = Table(v_rows, colWidths=[6.5 * cm, 3.5 * cm, 4.5 * cm, 2.5 * cm], repeatRows=1)
        vt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#EFF6FF")]),
        ]))
        story.append(vt)
    else:
        story.append(Paragraph("No valid vital readings recorded prior to referral.", ss["Field"]))
    story.append(Spacer(1, 5 * mm))

    # ── Abnormal Lab / OCR Flags ─────────────────────────────────────────
    story.append(Paragraph("4. Abnormal Lab &amp; OCR Biomarker Flags", ss["SectionHead"]))
    abnormal_rows: list[list[str]] = []
    for d in (documents or []):
        raw_ext = d.extracted_data if hasattr(d, "extracted_data") else d.get("extracted_data")
        if not raw_ext:
            continue
        try:
            parsed_ext = json.loads(raw_ext) if isinstance(raw_ext, str) else raw_ext
            for bm in (parsed_ext.get("biomarkers") or []):
                bm_status = str(bm.get("status") or "NORMAL").upper()
                if bm_status in ("HIGH", "LOW", "CRITICAL"):
                    abnormal_rows.append([
                        str(bm.get("parameter") or "—"),
                        str(bm.get("value") or "—"),
                        str(bm.get("unit") or "—"),
                        str(bm.get("reference_range") or "—"),
                        bm_status,
                    ])
        except Exception:
            continue

    if abnormal_rows:
        lab_tbl_data = [["Parameter", "Observed Value", "Unit", "Reference Range", "Flag"]] + abnormal_rows
        lt = Table(lab_tbl_data, colWidths=[4.8 * cm, 3.2 * cm, 2.5 * cm, 4.0 * cm, 2.5 * cm], repeatRows=1)
        lt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#9B1C1C")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#FEF2F2"), colors.white]),
        ]))
        story.append(lt)
    else:
        story.append(Paragraph("No abnormal OCR lab flags detected across uploaded documents.", ss["Field"]))
    story.append(Spacer(1, 5 * mm))

    # ── Stabilization Notes & Triage Rationale ───────────────────────────
    story.append(Paragraph("5. Stabilization Notes &amp; Triage Rationale", ss["SectionHead"]))
    if triage_decisions:
        latest_td = triage_decisions[0]
        td_reason = latest_td.reason if hasattr(latest_td, "reason") else latest_td.get("reason", "")
        story.append(Paragraph(f"<b>Triage Trigger / Override:</b> {td_reason}", ss["Field"]))
    if notes:
        for n in notes:
            ntype = n.note_type if hasattr(n, "note_type") else n.get("note_type", "general")
            ncontent = n.content if hasattr(n, "content") else n.get("content", "")
            story.append(Paragraph(f"<b>[{ntype.upper()}]</b> {ncontent}", ss["Field"]))
    else:
        story.append(Paragraph("Stabilization instructions: Maintain airway/oxygenation &amp; monitor vitals continuously en route via 108 Ambulance.", ss["Field"]))

    story.append(Spacer(1, 10 * mm))
    story.append(Paragraph("Referring Medical Officer Signature: ___________________________    Receiving Casualty MO: ___________________________", ss["Field"]))
    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph(f"Generated: {now_str}", ss["SmallRight"]))
    story.append(Paragraph(_NON_DIAGNOSTIC_FOOTER, ss["Disclaimer"]))

    doc.build(story)
    return buf.getvalue()
